export type AppColorScheme = {
  text: string;
  textSecondary: string;
  textMuted: string;
  background: string;
  backgroundSecondary: string;
  surface: string;
  surfaceElevated: string;
  surfaceBorder: string;
  tint: string;
  tintMuted: string;
  primary: string;
  onPrimary: string;
  link: string;
  icon: string;
  tabIconDefault: string;
  tabIconSelected: string;
  success: string;
  error: string;
  /** Hero / screen gradients */
  gradientStart: string;
  gradientMid: string;
  gradientEnd: string;
  /** Search / glass highlights */
  accentGlow: string;
  /** OTP / inputs */
  inputBorder: string;
  inputBorderFocus: string;
  inputFill: string;
};

export type ThemeDefinition = {
  id: ThemeId;
  label: string;
  tagline: string;
  light: AppColorScheme;
  dark: AppColorScheme;
};

function navTheme(
  mode: "light" | "dark",
  c: AppColorScheme,
): Theme {
  const base = mode === "dark" ? DarkTheme : DefaultTheme;
  return {
    ...base,
    colors: {
      ...base.colors,
      primary: c.tint,
      background: c.background,
      card: c.surface,
      text: c.text,
      border: c.surfaceBorder,
      notification: c.primary,
    },
  };
}

export function buildNavigationTheme(
  mode: "light" | "dark",
  c: AppColorScheme,
): Theme {
  return navTheme(mode, c);
}

/** Maps extended palette → legacy `Colors` shape for hooks */
export function toLegacyColors(c: AppColorScheme) {
  return {
    text: c.text,
    background: c.background,
    tint: c.tint,
    icon: c.icon,
    tabIconDefault: c.tabIconDefault,
    tabIconSelected: c.tabIconSelected,
  };
}

