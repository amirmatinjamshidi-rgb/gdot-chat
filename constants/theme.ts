import { DarkTheme, DefaultTheme, type Theme } from "@react-navigation/native";
import { Platform } from "react-native";

/** Keys consumed by `useThemeColor` and classic themed components */
export type ThemeColorName =
  | "text"
  | "background"
  | "tint"
  | "icon"
  | "tabIconDefault"
  | "tabIconSelected";

export type ThemeId =
  | "smashPulse"
  | "aurora"
  | "midnightGold"
  | "emberGlow"
  | "cyberTeal"
  | "cosmicViolet"
  | "slateSignal"
  | "forestMint"
  | "horizonSky"
  | "aurumVault"
  | "arcadeNeon"
  | "studioBlush"
  | "clinicWave"
